"""
HELIOS / Hikari — Quality Contracts & Verification Schemas
Shared typed Pydantic models for LLM Council, Cloudflare-inspired Security Audit,
and Evidence-based Acceptance Gates (unlazy methodology).
Zero sensitive credential storage; strict validation and stable IDs.
"""

from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


# ─── LLM Council Schemas ─────────────────────────────────────────────────────

class CouncilStatus(str, Enum):
    CONSENSUS = "consensus"
    NO_CONSENSUS = "no_consensus"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    PARTIAL_FAILURE = "partial_failure"
    FAILED = "failed"


class CouncilCandidateOpinion(BaseModel):
    """An independent opinion generated by a Council member model."""
    candidate_id: str = Field(description="Unique identifier for candidate e.g. 'candidate_a'")
    model_name: str = Field(description="Underlying model name")
    provider: str = Field(description="Provider name (pair, ollama, openrouter, gemini)")
    opinion_text: str = Field(description="Raw analysis and proposed solution")
    is_same_model_variant: bool = Field(
        default=False,
        description="True if this candidate shares model weights with another candidate"
    )
    latency_ms: Optional[float] = Field(default=None, description="Execution time in milliseconds")
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class CouncilRanking(BaseModel):
    """Anonymized peer review ranking submitted by a council member."""
    ranker_candidate_id: str = Field(description="Which candidate submitted this ranking")
    ranked_order: List[str] = Field(description="Ordered list of candidate IDs from best to worst")
    rationales: Dict[str, str] = Field(
        default_factory=dict,
        description="Critiques and justifications per candidate"
    )
    trade_offs: Dict[str, str] = Field(
        default_factory=dict,
        description="Identified edge cases or downsides"
    )


class CouncilResult(BaseModel):
    """The synthesized definitive recommendation from the Chairman model."""
    schema_version: str = "1.0.0"
    task_id: Optional[str] = None
    status: CouncilStatus = CouncilStatus.CONSENSUS
    decision: str = Field(description="The primary synthesized recommendation")
    alternatives: List[str] = Field(default_factory=list, description="Alternative approaches evaluated")
    disagreements: List[str] = Field(default_factory=list, description="Points of peer disagreement")
    confidence: float = Field(ge=0.0, le=1.0, description="Model self-assessed confidence level")
    evidence: Dict[str, Any] = Field(default_factory=dict, description="Supporting evidence or references")
    limitations: List[str] = Field(default_factory=list, description="Identified unknowns or assumptions")
    candidate_count: int = 0
    same_model_disclosure: Optional[str] = None
    provider_metadata: Dict[str, Any] = Field(default_factory=dict)
    budget_used: Dict[str, Any] = Field(default_factory=dict)
    candidates: List[CouncilCandidateOpinion] = Field(default_factory=list)
    rankings: List[CouncilRanking] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


# ─── Security Audit Schemas ──────────────────────────────────────────────────

class FindingSeverity(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class FindingLifecycleStatus(str, Enum):
    NEEDS_VALIDATION = "needs_validation"
    CONFIRMED = "confirmed"
    DISPROVED = "disproved"
    FIXED_PENDING_RETEST = "fixed_pending_retest"
    RESOLVED = "resolved"


class AuditFinding(BaseModel):
    """A structured vulnerability finding produced by the 6-phase audit harness."""
    finding_id: str = Field(description="Stable finding identifier e.g. 'SEC-2026-001'")
    schema_version: str = "1.0.0"
    run_id: str
    title: str
    severity: FindingSeverity
    confidence: float = Field(ge=0.0, le=1.0, description="Assessed likelihood of real-world exploitability")
    lifecycle_status: FindingLifecycleStatus = FindingLifecycleStatus.NEEDS_VALIDATION
    affected_file: str
    line_start: Optional[int] = None
    line_end: Optional[int] = None
    symbol: Optional[str] = None
    description: str
    attack_scenario: str
    evidence: str = Field(description="Direct code snippet or runtime proof")
    counterevidence_notes: Optional[str] = Field(
        default=None,
        description="Reasoning by the independent Verifier/Disprover"
    )
    remediation: str = Field(description="Actionable remediation steps")
    commit_hash: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class LedgerEntryStatus(str, Enum):
    COMPLETED = "completed"
    PENDING = "pending"
    SKIPPED = "skipped"
    NEEDS_REVIEW = "needs_review"


class CoverageLedgerEntry(BaseModel):
    """File-level audit tracking in .helios_audit_ledger.json."""
    file_path: str
    sha256_hash: str
    status: LedgerEntryStatus = LedgerEntryStatus.PENDING
    last_checked_at: Optional[str] = None
    rules_version: str = "1.0.0"
    skipped_reason: Optional[str] = None
    findings_count: int = 0


class CoverageLedger(BaseModel):
    """Resumable coverage ledger state."""
    schema_version: str = "1.0.0"
    audit_rules_version: str = "1.0.0"
    repo_path: str
    repo_revision: Optional[str] = None
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    entries: Dict[str, CoverageLedgerEntry] = Field(default_factory=dict)

    def is_file_stale(self, file_path: str, current_sha256: str) -> bool:
        entry = self.entries.get(file_path)
        if not entry:
            return True
        return entry.sha256_hash != current_sha256 or entry.status != LedgerEntryStatus.COMPLETED


class AuditReport(BaseModel):
    """Comprehensive target-neutral audit report."""
    run_id: str
    schema_version: str = "1.0.0"
    repo_revision: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    confirmed_findings: List[AuditFinding] = Field(default_factory=list)
    suspected_findings: List[AuditFinding] = Field(default_factory=list)
    disproved_findings: List[AuditFinding] = Field(default_factory=list)
    coverage_percentage: float = 0.0
    total_files_inspected: int = 0
    skipped_checks: List[Dict[str, str]] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    is_clean: bool = False


# ─── Evidence-Based Acceptance Gates (unlazy) ────────────────────────────────

class VerificationResult(BaseModel):
    """Verifiable proof of an individual check execution."""
    check_name: str
    command: Optional[str] = None
    exit_code: int = 0
    passed: bool = False
    stdout_preview: str = ""
    stderr_preview: str = ""
    duration_seconds: float = 0.0
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class AcceptanceGate(BaseModel):
    """
    Evidence-based acceptance gate.
    Requires verifiable execution proof. Missing or skipped checks can NEVER be counted as passed.
    """
    task_id: str
    required_tests: List[str] = Field(default_factory=list)
    required_lints: List[str] = Field(default_factory=list)
    required_security: List[str] = Field(default_factory=list)
    results: List[VerificationResult] = Field(default_factory=list)
    skipped_checks: List[Dict[str, str]] = Field(default_factory=list)

    def is_satisfied(self) -> bool:
        """Gate passes ONLY if all configured checks have run and passed with evidence."""
        passed_checks = {r.check_name: r.passed for r in self.results}
        
        for req in self.required_tests:
            if not passed_checks.get(req, False):
                return False
        for req in self.required_lints:
            if not passed_checks.get(req, False):
                return False
        for req in self.required_security:
            if not passed_checks.get(req, False):
                return False
        return True

    def get_summary(self) -> Dict[str, Any]:
        return {
            "passed": self.is_satisfied(),
            "total_executed": len(self.results),
            "total_passed": sum(1 for r in self.results if r.passed),
            "skipped": len(self.skipped_checks),
        }
